export function translate(lang, key, vars) {
  const dict = STRINGS[lang] || STRINGS.sv;
  let str =
    dict[key] !== undefined
      ? dict[key]
      : STRINGS.en[key] !== undefined
        ? STRINGS.en[key]
        : STRINGS.sv[key];
  if (str === undefined) return key;
  if (vars) {
    Object.keys(vars).forEach((k) => {
      str = String(str)
        .split("{" + k + "}")
        .join(vars[k]);
    });
  }
  return str;
}
